    private val byIdMap: Map<String, BiochemicalIngredient> = all.associateBy { it.id }

    val defaultIngredient: BiochemicalIngredient = byIdMap.getValue("glucose")

    fun byId(id: String): BiochemicalIngredient = byIdMap[id] ?: defaultIngredient

    fun forCoreParam(param: ManipulableParam): BiochemicalIngredient =
        all.firstOrNull { it.coreParam == param } ?: defaultIngredient

    fun search(query: String): List<BiochemicalIngredient> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return all
        return all.filter { ing ->
            ing.name.lowercase().contains(q) ||
                ing.symbol.lowercase().contains(q) ||
                ing.category.label.lowercase().contains(q) ||
                ing.category.badge.lowercase().contains(q) ||
                ing.targetRegion.displayName.lowercase().contains(q) ||
                ing.mechanism.lowercase().contains(q)
        }
    }
